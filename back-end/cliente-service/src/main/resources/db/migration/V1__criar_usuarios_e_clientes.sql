CREATE TABLE public.usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    funcao varchar(255) NOT NULL,
    login varchar(255) NOT NULL,
    senha varchar(255) NOT NULL,
    ativo boolean NOT NULL,
    versao bigint NOT NULL,

    CONSTRAINT usuarios_pkey PRIMARY KEY (id),
    CONSTRAINT uk_usuarios_login UNIQUE (login),
    CONSTRAINT usuarios_funcao_check
        CHECK (funcao IN ('ADMIN', 'CLIENTE', 'RECEPCIONISTA')),
    CONSTRAINT ck_usuarios_versao CHECK (versao >= 0)
);

CREATE TABLE public.clientes (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    cpf varchar(255) NOT NULL,
    email varchar(255) NOT NULL,
    nome varchar(255) NOT NULL,
    telefone varchar(255) NOT NULL,
    usuario_id integer,
    ativo boolean NOT NULL,
    versao bigint NOT NULL,

    CONSTRAINT clientes_pkey PRIMARY KEY (id),
    CONSTRAINT uk_clientes_cpf UNIQUE (cpf),
    CONSTRAINT uk_clientes_email UNIQUE (email),
    CONSTRAINT uk_clientes_telefone UNIQUE (telefone),
    CONSTRAINT uk_clientes_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_clientes_usuario
        FOREIGN KEY (usuario_id) REFERENCES public.usuarios (id),
    CONSTRAINT ck_clientes_versao CHECK (versao >= 0)
);