CREATE TABLE public.tipo_quarto (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    capacidade integer NOT NULL,
    nome varchar(255) NOT NULL,
    precodiario numeric(12, 2) NOT NULL,

    CONSTRAINT tipo_quarto_pkey PRIMARY KEY (id)
);

CREATE TABLE public.quartos (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    numero integer NOT NULL,
    status varchar(255) NOT NULL,
    id_tipo integer NOT NULL,

    CONSTRAINT quartos_pkey PRIMARY KEY (id),
    CONSTRAINT uk_quartos_numero UNIQUE (numero),
    CONSTRAINT fk_quartos_tipo
        FOREIGN KEY (id_tipo) REFERENCES public.tipo_quarto (id)
);